// SERVICE-BOUNDARY SEAM — apps/server's view of the agent turn runtime that
// `packages/agent` implements (Issue #16: "provider emits the frozen SSE
// event union via an event callback").
//
// Issue #16 is being built in parallel and does not exist on this branch yet.
// `routes/chat.ts` depends ONLY on this interface. At integration (Issue #20)
// the real `ClaudeAgentSdkProvider` (constructed by #16's provider factory
// over a concrete `ScadCoreApi`) is wired in here via `AppDeps.agent` — no
// route changes.
//
// Event ownership split (see routes/chat.ts for the full sequencing):
//   - the HOST (this server) emits `turn_started` before calling `runTurn`,
//     since it owns turn-id generation, timestamps, and the resolved
//     `max_passes` — none of which the provider should have to invent.
//   - the PROVIDER emits every other event, INCLUDING the closing
//     `turn_done` (it alone has the pass/usage accounting to fill it in).
//   - a `runTurn` promise that REJECTS (an unexpected provider crash, as
//     opposed to an expected in-band failure reported as an `error` event)
//     is caught by the route, which emits a synthetic `error` + `turn_done`
//     itself so the SSE stream always closes cleanly.
// ─────────────────────────────────────────────────────────────────────────────

import type { ChatImageInput, ParamValues, SseEvent } from "@scadforge/protocol";

export interface AgentTurnInput {
  projectId: string;
  /** Generated by the host before the turn starts; threaded through every event. */
  turnId: string;
  message: string;
  /** Always an array — the route normalizes an omitted `images` to `[]`. */
  images: ChatImageInput[];
  params?: ParamValues;
  /** Already clamped server-side; see `services/validation.ts#clampMaxPasses`. */
  maxPasses: number;
}

/** Called once per SSE frame the turn produces, in emission order. */
export type AgentEventSink = (event: SseEvent) => void;

export interface AgentProvider {
  /**
   * Runs one agent turn. Resolves once the turn has finished AND every event
   * has been handed to `onEvent` — in particular, a well-behaved
   * implementation calls `onEvent` with a `turn_done` event as its last call
   * before resolving. Expected failures (a tool error, a render failure) are
   * reported as an `error` event via `onEvent`, not a rejection.
   */
  runTurn(input: AgentTurnInput, onEvent: AgentEventSink): Promise<void>;
}

/**
 * The shape `packages/agent`'s Issue #16 provider factory is expected to
 * satisfy: `createAgentProvider(scadCore) => AgentProvider`. Not called
 * anywhere in this package (the composition root passes an already-built
 * `AgentProvider` into `createApp`) — kept here only so the intended
 * integration shape is typed and documented for Issue #20.
 */
export type AgentProviderFactory = (scadCore: import("./scad-core-api.js").ScadCoreApi) => AgentProvider;
